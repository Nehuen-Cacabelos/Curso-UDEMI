lista = [45, 23, 67, 12, 89, 90]

maximo = max(lista)  # Devuelve el valor máximo de la lista
minimo = min(lista)  # Devuelve el valor mínimo de la lista
print("Máximo:", maximo)
print("Mínimo:", minimo)

